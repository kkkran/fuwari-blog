// scripts/generate-icon-files.js
// 构建期把代码中实际用到的 Iconify 图标从本地 @iconify-json/* 包抽取为独立 SVG，
// 供 Icon.astro / IconSvelte.svelte 引用，替代运行时远程 api.iconify.design 请求。
// 未被本机安装包覆盖的合集（如 line-md / svg-spinners / fa6-solid）自动跳过，组件会回退远程。
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const srcDir = path.join(root, "src");
const outDir = path.join(root, "public", "local-icons");

// 已安装的图标合集（key 同时是 node_modules 下的包名）
const INSTALLED = new Set([
	"material-symbols",
	"material-symbols-light",
	"mingcute",
	"simple-icons",
	"fa6-solid",
	"mynaui",
	"arcticons",
]);

// 扫描 src 下所有源码里的图标字面量：collection:icon-name
function collectIconNames() {
	const iconRe = /["'`]([a-z0-9-]+:[a-zA-Z0-9-]+)["'`]/g;
	const names = new Set();
	const exts = new Set([".astro", ".svelte", ".ts", ".tsx", ".js", ".mjs"]);
	const walk = (dir) => {
		for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
			if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
			const full = path.join(dir, entry.name);
			if (entry.isDirectory()) walk(full);
			else if (exts.has(path.extname(entry.name))) {
				const content = fs.readFileSync(full, "utf8");
				let m;
				while ((m = iconRe.exec(content)) !== null) names.add(m[1]);
			}
		}
	};
	walk(srcDir);
	return names;
}

// 读取某合集的 icons.json（未安装返回 null）
const jsonCache = new Map();
function loadCollection(collection) {
	if (jsonCache.has(collection)) return jsonCache.get(collection);
	if (!INSTALLED.has(collection)) return null;
	const p = path.join(root, "node_modules", "@iconify-json", collection, "icons.json");
	if (!fs.existsSync(p)) return null;
	const data = JSON.parse(fs.readFileSync(p, "utf8"));
	jsonCache.set(collection, data);
	return data;
}

// 解析图标条目（含别名回溯），返回 { body, width, height }
function resolveIcon(data, name) {
	const seen = new Set();
	let cur = name;
	let icon = data.icons?.[cur];
	while (!icon && data.aliases?.[cur]) {
		if (seen.has(cur)) return null;
		seen.add(cur);
		cur = data.aliases[cur].parent;
		icon = data.icons?.[cur];
	}
	if (!icon) return null;
	const w = icon.width ?? data.width ?? 24;
	const h = icon.height ?? data.height ?? 24;
	return { body: icon.body, width: w, height: h };
}

function main() {
	const names = collectIconNames();
	if (fs.existsSync(outDir)) fs.rmSync(outDir, { recursive: true, force: true });
	fs.mkdirSync(outDir, { recursive: true });

	const available = [];
	const skipped = [];
	for (const full of [...names].sort()) {
		const idx = full.indexOf(":");
		if (idx <= 0) continue;
		const collection = full.slice(0, idx);
		const iconName = full.slice(idx + 1);
		const data = loadCollection(collection);
		const resolved = data ? resolveIcon(data, iconName) : null;
		if (!resolved) {
			skipped.push(full);
			continue;
		}
		const file = path.join(outDir, `${collection}-${iconName}.svg`);
		const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${resolved.width}" height="${resolved.height}" viewBox="0 0 ${resolved.width} ${resolved.height}">${resolved.body}</svg>\n`;
		fs.writeFileSync(file, svg, "utf8");
		available.push(full);
	}

	// 生成可用图标清单（供组件判断走本地还是远程）
	const manifestPath = path.join(srcDir, "utils", "local-icons.ts");
	const manifest = `// Auto-generated by scripts/generate-icon-files.js - DO NOT EDIT.\n` +
		`// Regenerated on every build from icon usage in src/.\n` +
		`export const localIconNames: readonly string[] = ${JSON.stringify(available)};\n`;
	fs.writeFileSync(manifestPath, manifest, "utf8");

	console.log(`[generate-icons] 生成 ${available.length} 个本地图标 -> public/local-icons/`);
	console.log(`[generate-icons] 跳过 ${skipped.length} 个（未安装合集/缺失，组件将回退远程）: ${skipped.join(", ")}`);
}

main();